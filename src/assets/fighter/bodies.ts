// 体型 4 種（b1〜b4）の、頭・胴体・腕・脚。オリジナルのデザイン（ファイターラボのマスコット）。
// 座標は types.ts のとおり（関節が原点のローカル座標）。右向きで、3/4 の見え方（顔は少し右寄り）。
// 輪郭線の太さ・陰影のつけ方（暗い重ね + 明るい重ね）・角の丸めは、全パーツで統一している。
import type { BodyDef, BodyId, Part, Shape } from './types.ts'

const o = (d: string, fill: Shape['fill'], sw?: number): Shape => ({
  d,
  fill,
  stroke: 'outline',
  sw,
})
/** 輪郭なしの塗り（陰影・模様） */
const f = (d: string, fill: Shape['fill']): Shape => ({ d, fill })
const part = (...shapes: Shape[]): Part => ({ shapes })

/** パスデータの座標を、原点（関節）を中心に、拡大縮小する（体型ごとの比率の違いに使う） */
const scalePath = (d: string, sx: number, sy: number) =>
  d.replace(/(-?\d*\.?\d+),(-?\d*\.?\d+)/g, (_, x: string, y: string) => {
    const r = (n: number) => String(Math.round(n * 100) / 100)
    return `${r(Number(x) * sx)},${r(Number(y) * sy)}`
  })
const scalePart = (p: Part, sx: number, sy: number): Part => ({
  shapes: p.shapes.map((s) => ({ ...s, d: scalePath(s.d, sx, sy) })),
})

