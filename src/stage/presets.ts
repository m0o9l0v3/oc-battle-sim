import type { StageData } from '../model/index.ts'
import { stageFromRows } from './rows.ts'

export type StagePreset = {
  id: string
  name: string
  /** 一覧に出す、短い説明（やさしい日本語） */
  description: string
  stage: StageData
}

const preset = (id: string, name: string, description: string, rows: string[]): StagePreset => ({
  id,
  name,
  description,
  stage: stageFromRows(rows, name),
})

