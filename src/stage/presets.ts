/** プリセットの一覧（1つ目が、標準。S04 に入ったときの初期選択） */
export const STAGE_PRESETS: readonly StagePreset[] = PRESETS

export const DEFAULT_PRESET_ID = STANDARD.id

export const findPreset = (id: string | null | undefined): StagePreset | undefined =>
  PRESETS.find((p) => p.id === id)

/** ステージの複製（プリセットを、エディタで直しても、元は変わらない） */
export const cloneStage = (s: StageData): StageData => ({
  ...s,
  cells: s.cells.map((r) => [...r]),
  spawns: { p1: { ...s.spawns.p1 }, p2: { ...s.spawns.p2 } },
})

/** プリセットの、作業用の複製。見つからないときは、標準（最後の拠り所） */
export const presetStage = (id: string | null | undefined): StageData =>
  cloneStage((findPreset(id) ?? STANDARD).stage)
